"""End-to-end run of the visit app with the real Whisper model and a synthetic (macOS `say`) technician.

The technician answers each prompt the way a person holding the true values would. Writes results/mvp/e2e.md.
Usage: PYTHONPATH=. .venv/bin/python scripts/mvp_e2e.py
"""

import json
import subprocess
import tempfile
import threading
import urllib.request
import uuid
from http.server import ThreadingHTTPServer
from pathlib import Path

from fvr.asr import transcribe
from mvp.server import App, make_handler

ROOT = Path(__file__).resolve().parents[1]
VOICE = "Samantha"
TRUTH = {
    "line_voltage": ("241", "volts"),
    "l1_amps": ("60", "amps"),
    "l2_amps": ("58", "amps"),
    "ground": ("25", "ohms"),
}
FIRST = {
    "line_voltage": "Line voltage is two forty one volts.",
    "l1_amps": "L one is pulling sixty amps.",
    "l2_amps": "L two is fifty one... fifty eight amps.",  # an uncued self-correction, like human line 33
    "ground": "Ground rod reads twenty five.",  # no unit
}
SPOKEN = {"241": "two forty one", "60": "sixty", "58": "fifty eight", "25": "twenty five"}
WORDS = {"volts": "volts", "amps": "amps", "ohms": "ohms"}


def speak(text: str, folder: Path) -> bytes:
    """Synthetic speech as 48 kHz 16-bit WAV, the format the browser sends."""
    aiff, out = folder / "x.aiff", folder / f"{uuid.uuid4().hex}.wav"
    subprocess.run(["say", "-v", VOICE, "-o", str(aiff), text], check=True)
    subprocess.run(["afconvert", "-f", "WAVE", "-d", "LEI16@48000", "-c", "1", str(aiff), str(out)], check=True)
    return out.read_bytes()


def silence(folder: Path) -> bytes:
    out = folder / "silence.wav"
    subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-f", "lavfi", "-i", "anullsrc=r=48000:cl=mono", "-t", "1.5",
                    "-c:a", "pcm_s16le", str(out)], check=True)  # fmt: skip
    return out.read_bytes()


def reply(prompt: dict) -> str:
    """What a technician who knows the true value says to this prompt."""
    value, unit = TRUTH[prompt["slot"]]
    if prompt["expect"] == "yesno":
        return "Yes." if f"{value} {WORDS[unit]}" in prompt["say"] else "No."
    return f"{SPOKEN[value]} {WORDS[unit]}."


class Client:
    def __init__(self, base: str, token: str, folder: Path):
        self.base, self.token, self.folder, self.log = base, token, folder, []

    def call(self, method: str, path: str, body: bytes | dict | None = None) -> dict:
        kind = "audio/wav" if isinstance(body, bytes) else "application/json"
        data = body if isinstance(body, bytes) else json.dumps(body).encode() if body is not None else None
        headers = {"X-Token": self.token, "Content-Type": kind}
        with urllib.request.urlopen(urllib.request.Request(self.base + path, data, headers, method=method)) as r:
            return json.loads(r.read())

    def say(self, vid: str, slot: str, text: str, audio: bytes | None = None) -> dict:
        audio = audio or speak(text, self.folder)
        state = self.call("POST", f"/api/visits/{vid}/audio?slot={slot}&utt={uuid.uuid4()}", audio)
        self.log.append((f"says: {text}", state["heard"], state["prompt"]))
        return state


def run(client: Client) -> dict:
    state = client.call("POST", "/api/visits", {"job": "demo-electrical"})
    vid = state["visit_id"]
    client.say(vid, "line_voltage", "(silence)", silence(client.folder))  # a recording with no speech
    state = client.say(vid, "line_voltage", "Hmm.")  # an unusable answer
    for _ in range(20):
        p = state["prompt"]
        if p["expect"] in ("reading", "value", "yesno"):
            first = p["expect"] == "reading"
            state = client.say(vid, p["slot"], FIRST[p["slot"]] if first else reply(p))
        elif p["expect"] == "readback":
            it = p["item"]
            right = (it["value"], it["unit"]) == TRUTH[it["slot"]]
            client.log.append((f"checks {it['label']}", "", {"say": f"{p['say']} {'Confirm' if right else 'Correct'}"}))
            state = client.call(
                "POST", f"/api/visits/{vid}/tap", {"action": "confirm" if right else "fix", "slot": it["slot"]}
            )
            if not right:
                state = client.say(vid, it["slot"], reply({"expect": "value", "slot": it["slot"]}))
        else:
            break
    return client.call("GET", f"/api/visits/{vid}/record")


def report(log: list, record: dict) -> str:
    lines = ["# MVP end-to-end run (real Whisper, synthetic voice)", "",
             f"Voice: macOS `{VOICE}`. Code {record['versions']['code']}. Generated by `scripts/mvp_e2e.py`.", "",
             "| Technician | Whisper heard | App asks next |", "|---|---|---|"]  # fmt: skip
    for said, heard, nxt in log:
        lines.append(f"| {said} | {heard} | {nxt.get('say', '')} |")
    lines += ["", "| Reading | Value | Status | By |", "|---|---|---|---|"]
    lines += [f"| {r['label']} | {r['value']} {r['unit']} | {r['status']} | {r['by']} |" for r in record["readings"]]
    correct = all((r["value"], r["unit"]) == TRUTH[r["key"]] for r in record["readings"])
    lines += ["", f"Record complete: {record['complete']}. All values match the truth: {correct}. "
              f"Audit: {record['audit']}. Read-back: {record['readback']}."]  # fmt: skip
    return "\n".join(lines) + "\n"


def main() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        folder = Path(tmp)
        app = App(folder / "data", ROOT / "mvp/jobs", transcribe, "e2e", None)
        httpd = ThreadingHTTPServer(("127.0.0.1", 0), make_handler(app))
        threading.Thread(target=httpd.serve_forever, daemon=True).start()
        client = Client(f"http://127.0.0.1:{httpd.server_port}", "e2e", folder)
        record = run(client)
        httpd.shutdown()
    out = ROOT / "results/mvp/e2e.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text(report(client.log, record))
    print(out.read_text())


if __name__ == "__main__":
    main()
